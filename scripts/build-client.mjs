#!/usr/bin/env node
/**
 * Build client/src/entry.jsx into the package-root client.bundle.js.
 *
 * The esbuild CLI is used instead of the JavaScript API: under the Windows
 * sandbox the API's piped child-process stdio is denied, while the CLI spawns
 * its native binary with inherited stdio. `.css` imports are compiled as text
 * modules (`--loader:.css=text`) and injected by the components' <style>.
 *
 * Why the wrapper: the component modules (including the map renderers) import
 * React at module scope. Emitting an IIFE and placing that whole IIFE inside
 * the DSH loader factory means every React lookup is resolved with the loader's
 * own `require`, never the page's missing global. The IIFE exports object is
 * returned from the factory as the plugin's `{ inject, apply }` face.
 *
 * React/ReactDOM stay external (the DSH module table provides them). MapLibre
 * MapLibre and their CSS are bundled.
 */
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import fsp from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const ENTRY = path.join(ROOT, 'client', 'src', 'entry.jsx')
const OUT = path.join(ROOT, 'client.bundle.js')
const BODY = path.join(ROOT, '.client.bundle.body.iife.js')
const META = path.join(ROOT, '.client.bundle.meta.json')
const GLOBAL_NAME = '__dshRoamPlannerEntry'

const pkg = JSON.parse(await fsp.readFile(path.join(ROOT, 'package.json'), 'utf8'))
if (!/(^|\/)dsh-roam-planner$/.test(pkg.name)) {
  throw new Error(`unexpected package name: ${pkg.name}`)
}

/**
 * Locate the native esbuild binary. The JavaScript API is not used because its
 * service process is spawned with piped stdio, which the Windows sandbox
 * denies (`spawn EPERM`). A direct binary (or the CLI shim, which itself uses
 * inherited stdio) avoids that.
 */
function resolveEsbuildExecutable() {
  const fromEnv = process.env.ESBUILD_BINARY_PATH
  if (fromEnv && fs.existsSync(fromEnv)) return { command: fromEnv, prefix: [] }

  const platformPackage = `@esbuild/${process.platform}-${process.arch}`
  const binary = process.platform === 'win32' ? 'esbuild.exe' : path.join('bin', 'esbuild')
  try {
    return { command: require.resolve(`${platformPackage}/${binary}`), prefix: [] }
  } catch (_error) {
    /* Fall through to esbuild's Node CLI shim. */
  }

  const main = require.resolve('esbuild')
  const packageRoot = path.resolve(path.dirname(main), '..')
  const manifest = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8'))
  const bin = typeof manifest.bin === 'string' ? manifest.bin : manifest.bin && manifest.bin.esbuild
  if (!bin) throw new Error('installed esbuild package declares no CLI bin')
  return { command: process.execPath, prefix: [path.join(packageRoot, bin)] }
}

const esbuild = resolveEsbuildExecutable()
const args = [
  '--bundle',
  '--format=iife',
  `--global-name=${GLOBAL_NAME}`,
  '--platform=browser',
  '--target=es2020',
  '--jsx=transform',
  '--jsx-factory=React.createElement',
  '--jsx-fragment=React.Fragment',
  '--external:react',
  '--external:react-dom',
  '--minify',
  '--legal-comments=none',
  '--loader:.css=text',
  `--outfile=${BODY}`,
  `--metafile=${META}`,
  '--log-level=warning',
  ENTRY,
]

try {
  const result = spawnSync(esbuild.command, [...esbuild.prefix, ...args], {
    cwd: ROOT,
    stdio: 'inherit',
    windowsHide: true,
  })
  if (result.error) throw result.error
  if (result.status !== 0) throw new Error(`esbuild exited with status ${result.status}`)

  const body = (await fsp.readFile(BODY, 'utf8')).trimEnd()
  const metafile = JSON.parse(await fsp.readFile(META, 'utf8'))

  const bundle = `/* ${pkg.name} client bundle.
 * Generated by scripts/build-client.mjs from client/src/entry.jsx. Do not edit.
 */
window.__ModuleLoader__.load({
  id: '${pkg.name}',
  factory(require) {
${body}

    return ${GLOBAL_NAME};
  },
});
`

  for (const needle of [`id: '${pkg.name}'`, pkg.name, 'roam-planner']) {
    if (!bundle.includes(needle)) {
      throw new Error(`bundle is missing expected marker: ${needle}`)
    }
  }
  // With --format=iife esbuild resolves an external through its local
  // `typeof require === "function"` shim, so the call site is `_u("react")`
  // rather than a literal `require("react")`. Both mean the same thing here:
  // the module is resolved by the factory's `require`, not bundled.
  const reactReference = /(?:require|[A-Za-z_$][\w$]*)\(\s*["']react["']\s*\)/.test(bundle)
  if (!reactReference) {
    throw new Error('React was not kept external: the bundle has no React require call')
  }
  if (bundle.includes('react.production.min') || bundle.includes('Symbol.for("react.element")')) {
    throw new Error('React appears to be bundled instead of external')
  }
  const globalMentions = bundle.split(GLOBAL_NAME).length - 1
  if (globalMentions < 2) {
    throw new Error('esbuild did not emit the IIFE global export object')
  }

  await fsp.writeFile(OUT, bundle, 'utf8')

  const inputNames = Object.keys(metafile.inputs || {})
  const hasMaplibre = inputNames.some((name) => /(^|[\\/])maplibre-gl([\\/]|$)/.test(name))
  const bytes = Buffer.byteLength(bundle, 'utf8')
  const kib = (bytes / 1024).toFixed(1)

  console.log(`[build-client] wrote ${path.relative(ROOT, OUT)} (${bytes} bytes, ${kib} KiB)`)
  console.log(
    `[build-client] react external: yes (factory require); maplibre-gl bundled: ${hasMaplibre ? 'yes' : 'no'}`,
  )
} finally {
  await Promise.all([
    fsp.rm(BODY, { force: true }),
    fsp.rm(META, { force: true }),
  ])
}
